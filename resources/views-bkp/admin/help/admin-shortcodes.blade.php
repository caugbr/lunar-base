<div class="help-content">
    <div class="help-header">
        <h3>
            <x-lucide-help-circle class="lucid-icon" />
            Referência de Shortcodes
        </h3>
        <p>Catálogo de códigos de atalho suportados pelo editor de texto em páginas e posts.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>Como Utilizar:</strong>
                Copie o exemplo do shortcode desejado (incluindo os colchetes <code>[...]</code>) e cole diretamente no corpo do texto no editor TinyMCE de qualquer post ou página.
            </li>
            <li>
                <strong>Origem (Core vs. Plugin):</strong>
                Identifica se a tag faz parte dos recursos nativos do Lunar Base (como <code>[embed]</code>, <code>[link]</code>) ou se foi injetada por um plugin ativo (como mapas, formulários ou botões).
            </li>
            <li>
                <strong>Atributos e Parâmetros:</strong>
                Consulte a lista de atributos suportados por cada tag para personalizar dimensões, URLs, estilos e opções obrigatórias.
            </li>
            <li>
                <strong>Filtro de Visualização:</strong>
                Alterne entre visualizar todos os shortcodes, apenas os do <em>Core</em> ou apenas os originados por <em>Plugins ativos</em>.
            </li>
        </ul>
    </div>

    <div class="help-footer">
        <div>
            <x-lucide-info class="lucid-icon" />
            <div>
                Se um plugin for desativado, seus shortcodes correspondentes deixarão de ser processados no front-end.
            </div>
        </div>
    </div>
</div>
