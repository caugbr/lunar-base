<div class="help-content">
    <div class="help-header">
        <h3>
            <x-lucide-help-circle class="lucid-icon" />
            Criar Novo Post
        </h3>
        <p>Redija, formate e publique um novo artigo ou notícia para o seu público.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>Título e Conteúdo Obrigatórios:</strong>
                Informe o título do artigo e use o editor visual (TinyMCE) para redigir o texto. Você pode incluir imagens, vídeos, títulos, listas e blocos de citação.
            </li>
            <li>
                <strong>Data de Publicação e Agendamento:</strong>
                Por padrão, o post é publicado com a data atual. Caso defina uma data futura e mantenha o status como <em>Publicado</em>, o post ficará agendado para ir ao ar no momento correto.
            </li>
            <li>
                <strong>Descrição Curta (Resumo):</strong>
                Utilizada nos cards de listagem e nas prévias de redes sociais. Se deixada em branco, o sistema gerará um resumo automático a partir dos primeiros parágrafos do texto.
            </li>
            <li>
                <strong>Taxonomias (Categorias e Tags):</strong>
                Vincule o post aos assuntos correspondentes na seção lateral para facilitar a navegação dos leitores por temas relacionados.
            </li>
            <li>
                <strong>Imagem de Destaque (Thumbnail):</strong>
                Insira a capa do post através da Biblioteca de Mídia ou fazendo o upload direto de uma nova imagem.
            </li>
            <li>
                <strong>Opções Especiais:</strong>
                <ul>
                    <li><strong>Destacar na home:</strong> Exibe o post em áreas especiais do tema ativo.</li>
                    <li><strong>Fixar no topo:</strong> Mantém o post na primeira posição do blog.</li>
                </ul>
            </li>
        </ul>
    </div>

    <div class="help-footer">
        <p>
            <x-lucide-info class="lucid-icon" />
            Para salvar sem publicar imediatamente, altere o status para <strong>Rascunho</strong> antes de clicar em Salvar.
        </p>
    </div>
</div>
