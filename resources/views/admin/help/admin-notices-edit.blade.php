<div class="help-content">
    <div class="help-header">
        <h3>
            <x-lucide-help-circle class="lucid-icon" />
            Editar aviso
        </h3>
        <p>Configure a mensagem, a aparência e para quem o comunicado será exibido no painel.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>Mensagem do aviso:</strong>
                Escreva o texto com clareza. Você pode usar formatações HTML simples, como <code>&lt;strong&gt;</code> para destaque e <code>&lt;a href="..."&gt;</code> para adicionar links.
            </li>
            <li>
                <strong>Tipo de alerta:</strong>
                Define a cor e o ícone do aviso. Use <em>Informativo</em> para recados gerais, <em>Aviso</em> para manutenções programadas, <em>Crítico</em> para falhas ou alertas urgentes e <em>Sucesso</em> para comemorações ou metas atingidas.
            </li>
            <li>
                <strong>Segmentação de destinatários:</strong>
                Escolha se o comunicado deve aparecer para toda a equipe, apenas para determinados perfis (como apenas autores ou editores) ou selecione pessoas individualmente.
            </li>
            <li>
                <strong>Data de expiração:</strong>
                Campo opcional. Se preenchido, o sistema remove o aviso do ar automaticamente na data e hora selecionadas, evitando comunicados desatualizados no painel.
            </li>
            <li>
                <strong>Aviso ativo:</strong>
                Mantenha marcado como <em>Sim</em> para publicar imediatamente, ou escolha <em>Não</em> caso queira deixar o texto pronto como rascunho para ativar mais tarde.
            </li>
        </ul>
    </div>

    <div class="help-footer">
        <div>
            <x-lucide-info class="lucid-icon" />
            <div>
                Lembre-se de clicar em <strong>Publicar aviso</strong> para salvar as configurações.
            </div>
        </div>
    </div>
</div>
