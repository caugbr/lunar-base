            Editar Página
        </h3>
        <p>Modifique o conteúdo, estrutura visual e propriedades da página selecionada.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>Editor de Conteúdo:</strong>
                Utilize a barra de ferramentas do TinyMCE para formatar textos, links, tabelas e alinhar elementos. Você pode subir novas mídias ou escolher imagens da biblioteca diretamente pelo topo do editor.
            </li>
            <li>
                <strong>Aviso de Alterações Não Salvas:</strong>
                O sistema monitora o formulário. Caso tente sair da tela sem salvar as modificações feitas, um alerta de confirmação impedirá a perda acidental do seu trabalho.
            </li>
            <li>
                <strong>Alteração de Slug (URL):</strong>
                Se você modificar o slug de uma página que já está indexada ou compartilhada, lembre-se de que os links antigos externos podem parar de funcionar.
            </li>
            <li>
                <strong>Template Visual:</strong>
                Permite alternar o layout de exibição da página no tema ativo (ex: largura total, com barra lateral, landing page, etc.).
            </li>
            <li>
                <strong>Hierarquia (Página Mãe):</strong>
                Define se esta página é uma subpágina de outra já existente (a página atual é automaticamente excluída da lista para evitar referências circulares).
            </li>
            <li>
                <strong>Imagem de Destaque:</strong>
                Utilizada para ilustrar o topo da página no front-end e nas prévias de compartilhamento em redes sociais (OpenGraph/WhatsApp).
            </li>
        </ul>
    </div>

