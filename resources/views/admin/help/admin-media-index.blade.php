<div class="help-content">
    <div class="help-header">
        <h3>
            <x-lucide-help-circle class="lucid-icon" />
            Biblioteca de Mídia
        </h3>
        <p>Central de armazenamento e gerenciamento de imagens, documentos e arquivos do site.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>Upload de Arquivos:</strong>
                Clique no botão <strong>Upload</strong> no topo para enviar novos arquivos. Você pode arrastar imagens ou documentos diretamente para a área indicada ou selecionar do seu computador.
            </li>
            <li>
                <strong>Formatos e Limites Suportados:</strong>
                O sistema aceita imagens (JPG, PNG, WebP, GIF, SVG) e documentos (como PDF). O limite padrão recomendado por arquivo é de até <strong>10 MB</strong>.
            </li>
            <li>
                <strong>Visualização e Detalhes:</strong>
                Clique sobre qualquer item na grade para abrir a prévia, visualizar a URL pública completa, o tamanho do arquivo, as dimensões em pixels e a data de envio.
            </li>
            <li>
                <strong>Edição e Metadados (Texto Alternativo / Alt):</strong>
                Ao editar uma mídia, preencha sempre o campo <em>Texto Alternativo (Alt Text)</em>. Isso melhora a acessibilidade para deficientes visuais e otimiza o rankeamento do site nos mecanismos de busca (SEO do Google Imagens).
            </li>
            <li>
                <strong>Uso em Páginas e Posts:</strong>
                Todas as mídias enviadas aqui ficam instantaneamente disponíveis para seleção rápida nos editores de texto, nas capas de posts e nas imagens de destaque de páginas.
            </li>
            <li>
                <strong>Exclusão de Mídias:</strong>
                Ao remover um arquivo da biblioteca, ele será apagado do servidor. Certifique-se de que a imagem ou documento não esteja em uso em nenhuma página pública ativa antes de excluir.
            </li>
        </ul>
    </div>

    <div class="help-footer">
        <p>
            <x-lucide-info class="lucid-icon" />
            Utilize imagens no formato <strong>WebP</strong> ou comprimidas para garantir que as páginas do seu site carreguem de forma ultrarrápida.
        </p>
    </div>
</div>
