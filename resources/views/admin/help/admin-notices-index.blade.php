<div class="help-content">
    <div class="help-header">
        <h3>
            <x-lucide-help-circle class="lucid-icon" />
            Avisos do sistema
        </h3>
        <p>Gerencie comunicados e alertas direcionados aos usuários do painel administrativo.</p>
    </div>

    <div class="help-body">
        <ul class="help-list">
            <li>
                <strong>O que são avisos persistentes:</strong>
                São mensagens exibidas no topo do painel que permanecem visíveis em todas as páginas até que o usuário clique no botão de fechar (X).
            </li>
            <li>
                <strong>Público-alvo:</strong>
                Avisos podem ser globais (visíveis para todos), restritos a determinados perfis de acesso (roles) ou enviados apenas para usuários específicos.
            </li>
            <li>
                <strong>Status (Ativo / Inativo):</strong>
                Você pode pausar a exibição de qualquer comunicado desativando seu status, sem perder o registro ou o histórico de leituras.
            </li>
            <li>
                <strong>Contador de leituras:</strong>
                O ícone com o número de leituras indica quantos usuários únicos já visualizaram e dispensaram o aviso clicando no botão de fechar.
            </li>
            <li>
                <strong>Expiração automática:</strong>
                Avisos com data de término configurada deixam de ser exibidos automaticamente após o prazo, mesmo que o usuário não os tenha fechado.
            </li>
        </ul>
    </div>

    <div class="help-footer">
        <div>
            <x-lucide-info class="lucid-icon" />
            <div>
                Para criar um novo comunicado para a equipe, clique no botão <strong>Novo aviso</strong>.
            </div>
        </div>
    </div>
</div>
